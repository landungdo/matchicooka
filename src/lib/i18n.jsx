export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => {
    try { return localStorage.getItem("mx_lang") || "en"; } catch { return "en"; }
  });
  useEffect(() => { try { localStorage.setItem("mx_lang", lang); } catch {} }, [lang]);

  const t = (key, vars) => {
    let str = (DICT[lang] && DICT[lang][key]) || DICT.en[key] || key;
    if (vars) for (const k in vars) str = str.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]);
    return str;
  };

  return <LangCtx.Provider value={{ lang, setLang, t }}>{children}</LangCtx.Provider>;
}

export function useLang() {
  return useContext(LangCtx) || { lang: "en", setLang: () => {}, t: (k) => k };
}
